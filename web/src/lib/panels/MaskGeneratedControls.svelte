<script lang="ts">
  import DualRangeSlider from '$lib/components/editor/controls/DualRangeSlider.svelte';
  import SliderRow from '$lib/components/editor/controls/SliderRow.svelte';
  import Notice from '$lib/components/Notice.svelte';
  import { editor } from '$lib/stores/editor.svelte';
  import type { MaskComponent } from '$lib/types/edits';
  import { Tooltip } from '@immich/ui';
  import { mergeProps } from 'bits-ui';

  let { layerId, component }: { layerId: string; component: MaskComponent } = $props();

  const meta = $derived(component.generated);

  let syncedId = $state<string | null>(null);
  let grow = $state(0);
  let featherPx = $state(0);
  let depthMin = $state(0);
  let depthMax = $state(1);
  let depthSoftness = $state(0.1);

  $effect(() => {
    if (component.id === syncedId) return;
    syncedId = component.id;
    grow = meta?.grow ?? 0;
    featherPx = meta?.feather ?? 0;
    depthMin = meta?.range?.min ?? 0;
    depthMax = meta?.range?.max ?? 1;
    depthSoftness = meta?.range?.softness ?? 0.1;
  });

  function label(kind: string): string {
    if (kind === 'subject') return 'Subject';
    if (kind === 'people') return 'People';
    if (kind === 'sky') return 'Sky';
    if (kind === 'depth') return 'Depth';
    if (kind === 'semantic') return 'Scene';
    if (kind === 'click') return 'Click to select';
    return kind;
  }

  async function rebake(): Promise<void> {
    if (!meta) return;
    const range =
      meta.kind === 'depth' ? { min: depthMin, max: depthMax, softness: depthSoftness } : undefined;
    const sameRange =
      !range ||
      (range.min === (meta.range?.min ?? 0) &&
        range.max === (meta.range?.max ?? 1) &&
        range.softness === (meta.range?.softness ?? 0.1));
    const unchanged = sameRange && grow === (meta.grow ?? 0) && featherPx === (meta.feather ?? 0);
    if (unchanged && !meta.painted) return;
    await editor.rebakeGeneratedComponent(layerId, component.id, grow, featherPx, range);
  }
</script>

{#if meta}
  <div class="mt-1.5 flex flex-col gap-1.5">
    <Tooltip text="Generated by {meta.model_id}">
      {#snippet child({ props })}
        <div
          {...mergeProps(props, { tabindex: -1 })}
          class="px-1 text-[10px] uppercase tracking-wider text-dark/65"
        >
          {label(meta.kind)}{meta.class ? ` · ${meta.class}` : ''}
        </div>
      {/snippet}
    </Tooltip>
    {#if meta.painted}
      <Notice
        color="warning"
        message="You have painted on this mask. Moving these sliders regenerates it from the model and discards those strokes."
        class="mx-1"
      />
    {/if}
    {#if meta.kind === 'depth'}
      <div class="panel-row h-7 items-center rounded-sm px-0.5 transition-colors hover:bg-white/3">
        <span class="truncate text-[11px] font-medium text-dark/65 select-none">Near → Far</span>
        <DualRangeSlider
          value={[depthMin, depthMax]}
          min={0}
          max={1}
          step={0.01}
          defaultValue={[0, 1]}
          thumbLabels={['Near limit', 'Far limit']}
          valueText={(v: number) => `${Math.round(v * 100)}% of the photo is nearer`}
          onLive={([near, far]) => {
            depthMin = near;
            depthMax = far;
          }}
          onCommit={rebake}
        />
        <span class="px-1 text-right font-mono text-[10px] text-dark/65 tabular-nums">
          {Math.round(depthMin * 100)}–{Math.round(depthMax * 100)}
        </span>
      </div>
      <SliderRow
        label="Softness"
        value={depthSoftness}
        min={0}
        max={1}
        step={0.01}
        defaultValue={0.1}
        onLive={(v: number) => (depthSoftness = v)}
        onCommit={rebake}
        format={(v: number) => v.toFixed(2)}
      />
    {/if}
    <SliderRow
      label="Grow"
      value={grow}
      min={-32}
      max={32}
      step={1}
      defaultValue={0}
      onLive={(v: number) => (grow = v)}
      onCommit={rebake}
      format={(v: number) => v.toFixed(0)}
    />
    <SliderRow
      label="Feather"
      value={featherPx}
      min={0}
      max={32}
      step={1}
      defaultValue={0}
      onLive={(v: number) => (featherPx = v)}
      onCommit={rebake}
      format={(v: number) => v.toFixed(0)}
    />
  </div>
{/if}
